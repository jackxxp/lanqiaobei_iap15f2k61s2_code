//drv_temp.h
#ifndef __DRV_TEMP_H__
#define __DRV_TEMP_H__

#include "sys_main.h"

// 引脚定义
sbit DQ = P1^4;

//==============================================================================
// 函数说明：初始化DS18B20
// 返回值：0-初始化成功 1-初始化失败
//==============================================================================
bit init_ds18b20(void);

//==============================================================================
// 函数说明：DS18B20完整初始化并设置11位分辨率
// 返回值：0-初始化成功 1-初始化失败
//==============================================================================
bit Temp_Init(void);

//==============================================================================
// 函数说明：设置DS18B20分辨率
// 参数：res - 0x1F=9位, 0x3F=10位, 0x5F=11位, 0x7F=12位
//==============================================================================
void set_resolution(unsigned char res);

//==============================================================================
// 函数说明：写入一个字节
//==============================================================================
void Write_DS18B20(unsigned char dat);

//==============================================================================
// 函数说明：读取一个字节
//==============================================================================
unsigned char Read_DS18B20(void);

//==============================================================================
// 函数说明：读取温度值（返回*10格式）
//==============================================================================
int read_temp_int(void);

#endif
